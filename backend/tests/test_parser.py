def _normalise(text: str) -> str:
    return re.sub(r"\s+", " ", text)


def _check(name: str) -> list[str]:
    """Return a list of problems for one fixture (empty list = extracted correctly)."""
    expected = EXPECTED[name]
    text = _normalise(extract_text((FIXTURES / name).read_bytes()).text)
    problems = [f"missing {p!r}" for p in expected["contains"] if p not in text]
    problems += [f"should be removed: {p!r}" for p in expected.get("absent", []) if p in text]
    positions = [text.find(p) for p in expected["order"]]
    if -1 in positions or positions != sorted(positions):
        problems.append(f"wrong order for {expected['order']}")
    return problems


def test_objective_1_at_least_9_of_10_fixtures_extract_correctly() -> None:
    results = {name: _check(name) for name in EXPECTED}
    correct = sum(1 for problems in results.values() if not problems)
    report = "\n".join(f"{'PASS' if not p else 'FAIL'}  {n}  {'; '.join(p)}" for n, p in results.items())
    print(f"\nObjective 1: {correct} of {len(EXPECTED)} fixture PDFs extracted correctly\n{report}")
    assert len(EXPECTED) == 10
    assert correct >= 9, report


@pytest.mark.parametrize("name", ["scanned.pdf", "blank.pdf", "truncated.pdf"])
def test_unreadable_pdfs_raise_unreadable_pdf(name: str) -> None:
    with pytest.raises(UnreadablePdf) as excinfo:
        extract_text((FIXTURES / name).read_bytes())
    assert excinfo.value.code == "unreadable_pdf"


def test_corrupt_file_renamed_pdf_raises_invalid_file_type() -> None:
    with pytest.raises(InvalidPdf) as excinfo:
        extract_text((FIXTURES / "corrupt.pdf").read_bytes())
    assert excinfo.value.code == "invalid_file_type"


def test_empty_bytes_are_not_a_pdf() -> None:
    with pytest.raises(InvalidPdf):
        extract_text(b"")


def test_page_count_lines_and_fonts() -> None:
    parsed = extract_text((FIXTURES / "six_pages.pdf").read_bytes())
    assert parsed.pages == 6
    assert {line.page for line in parsed.lines} == set(range(1, 7))
    first = parsed.lines[0]
    assert first.text == "Vikram Rao"
    assert 0 <= first.x0 < first.x1 and 0 <= first.top < first.bottom
    assert first.size == pytest.approx(18, abs=0.5)

    fonts = extract_text((FIXTURES / "multi_font.pdf").read_bytes()).fonts
    assert fonts == ["Courier", "Helvetica", "Times"]


def test_lines_keep_raw_glyphs_for_ats_but_text_is_readable() -> None:
    parsed = extract_text((FIXTURES / "sample_resume_backend.pdf").read_bytes())
    assert any(line.text.startswith("(cid:") for line in parsed.lines)  # raw form kept for the ATS bullet check
    assert "(cid:" not in parsed.text
    assert "• Built REST APIs" in parsed.text


# --- clean_text -------------------------------------------------------------


def test_clean_text_lowercases_and_removes_identifiers() -> None:
    text = "Asha Verma\nasha.verma@example.com | +91 98765 43210 | https://github.com/asha | linkedin.com/in/asha\nPython"
    cleaned = clean_text(text)
    assert cleaned == "asha verma python"


def test_clean_text_keeps_tech_tokens() -> None:
    cleaned = clean_text("Skills: C++, C#, Node.js, .NET, ASP.NET, CI/CD, Socket.IO, scikit-learn.")
    assert cleaned.split() == ["skills", "c++", "c#", "node.js", ".net", "asp.net", "ci/cd", "socket.io", "scikit-learn"]


def test_clean_text_keeps_year_ranges_and_percentages_digits() -> None:
    cleaned = clean_text("Analyst (2019 - 2021), improved accuracy by 35%")
    assert "2019" in cleaned and "2021" in cleaned and "35" in cleaned


def test_clean_text_removes_bullets_and_address_lines() -> None:
    text = "• Built APIs\n▪ Wrote tests\n- Fixed bugs\n12 MG Road, Pune 411001\nPython · Go"
    assert clean_text(text) == "built apis wrote tests fixed bugs python go"


def test_clean_text_light_keeps_case_and_lines() -> None:
    text = "• Built REST APIs with FastAPI.\nContact: a@b.com\n\n  Python · Go  "
    assert clean_text_light(text) == "Built REST APIs with FastAPI.\nContact:\nPython, Go"


def test_strip_name_header_removes_name_only() -> None:
    text = "Asha Verma\nBackend developer\nSKILLS\nPython"
    assert strip_name_header(text) == "Backend developer\nSKILLS\nPython"


def test_strip_name_header_ignores_section_headings_and_late_lines() -> None:
    assert strip_name_header("Professional Summary\nI build APIs.") == "Professional Summary\nI build APIs."
    text = "I build APIs.\nMore text here.\nAnd more.\nAsha Verma"
    assert strip_name_header(text) == text


def test_remove_stopwords() -> None:
    assert remove_stopwords("experience with python and the react library") == "experience python react library"
